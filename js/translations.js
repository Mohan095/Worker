/**
 * Get current application language (defaults to 'en')
 */
export function getAppLanguage() {
  const stored = localStorage.getItem("work_connect_lang");
  if (stored && translations[stored]) {
    return stored;
  }
  return "en";
}

/**
 * Set application language in localStorage
 */
export function setAppLanguage(lang) {
  if (translations[lang]) {
    localStorage.setItem("work_connect_lang", lang);
    return true;
  }
  return false;
}

/**
 * Translate a key into the active language
 */
export function t(key, lang = null) {
  const currentLang = lang || getAppLanguage();
  const dict = translations[currentLang] || translations.en;
  return dict[key] || translations.en[key] || key;
}

/**
 * Auto-translate all elements with `data-i18n` or `data-i18n-placeholder`
 */
export function applyPageTranslations(lang = null) {
  const currentLang = lang || getAppLanguage();
  document.documentElement.lang = currentLang;

  // Replace textContent
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const translated = t(key, currentLang);
    if (translated) {
      el.textContent = translated;
    }
  });

  // Replace placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    const translated = t(key, currentLang);
    if (translated) {
      el.setAttribute("placeholder", translated);
    }
  });

  // Replace titles
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    const translated = t(key, currentLang);
    if (translated) {
      el.setAttribute("title", translated);
    }
  });
}
